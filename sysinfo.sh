#!/bin/bash

# 1. СПИСОК ХОСТОВ
# Создаем массив (список) из адресов. 
hosts=("8.8.8.8" "google.com" "localhost" "192.168.1.100" "ya.ru")


# 2. ПОДГОТОВКА ФАЙЛА ДЛЯ ЛОГА
# Получаем текущую дату в формате ГГГГ-ММ-ДД (например, 2023-10-25)
current_date=$(date +%Y-%m-%d)

# Формируем имя файла, например: ping_log_2023-10-25.txt
log_file="ping_log_${current_date}.txt"

# Записываем в файл заголовок (создаем файл, если его нет, или добавляем в конец)
echo "=== Проверка хостов на $(date +%H:%M:%S) ===" >> "$log_file"


# 3. ЦИКЛ ПРОВЕРКИ
# Проходимся по каждому хосту из нашего списка
for host in "${hosts[@]}"
do
    # Команда ping:
    # -c 1  -> отправить только 1 пакет
    # -W 1  -> ждать ответа максимум 3 секунды (чтобы не зависать)
    # > /dev/null 2>&1 -> скрыть весь технический вывод пинга с экрана
    
    if ping -c 1 -W 3 "$host" > /dev/null 2>&1
    then
        # Если пинг успешен (код возврата 0)
        message="[+] $host - ДОСТУПЕН"
        echo "$message"
        echo "$message" >> "$log_file"
    else
        # Если пинг не прошел
        message="[-] $host - НЕДОСТУПЕН"
        echo "$message"
        echo "$message" >> "$log_file"
    fi
done

# Добавляем пустую строку в конец лога для красоты
echo "" >> "$log_file"

echo "======================================"
echo "Проверка завершена. Результаты сохранены в: $log_file"
